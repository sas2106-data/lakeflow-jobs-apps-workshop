"""Claims Genie — a Streamlit Databricks App that chats with a Genie space over the gold claims tables."""
import os

import pandas as pd
import streamlit as st
from databricks.sdk import WorkspaceClient

st.set_page_config(page_title="Claims Genie", page_icon="💬", layout="wide")

SPACE_ID = os.getenv("GENIE_SPACE_ID")
try:
    headers = st.context.headers
except AttributeError:  # older Streamlit
    headers = {}
user = headers.get("X-Forwarded-Preferred-Username") or headers.get("X-Forwarded-Email") or "there"
user_token = headers.get("X-Forwarded-Access-Token")


def client() -> WorkspaceClient:
    """Module 6: with user authorization the app gets the signed-in user's token, so Genie runs with
    *their* Unity Catalog permissions. Without it, the app's service principal is used."""
    if user_token:
        return WorkspaceClient(host=os.environ["DATABRICKS_HOST"], token=user_token, auth_type="pat")
    return WorkspaceClient()


st.title("💬 Claims Genie")
st.caption(f"Hello, {user.split('@')[0]}! Ask a question about claims in plain English.")
with st.sidebar:
    st.subheader("How this app connects")
    st.markdown(f"**Genie space:** `{SPACE_ID or 'not configured'}`")
    st.markdown("**Runs as:** " + ("you (user authorization)" if user_token else "the app's service principal"))
    if st.button("New conversation"):
        st.session_state.clear()
        st.rerun()

if not SPACE_ID:
    st.error("Add a Genie space resource named `genie-space` to the app (Module 4).")
    st.stop()

st.session_state.setdefault("history", [])
st.session_state.setdefault("conversation_id", None)


def render(answer: dict):
    if answer.get("text"):
        st.markdown(answer["text"])
    if answer.get("description"):
        st.markdown(answer["description"])
    if answer.get("df") is not None:
        st.dataframe(answer["df"], hide_index=True, use_container_width=True)
    if answer.get("sql"):
        with st.expander("SQL generated by Genie"):
            st.code(answer["sql"], language="sql")


def ask(question: str) -> dict:
    w = client()
    conv = st.session_state.conversation_id
    msg = (w.genie.create_message_and_wait(SPACE_ID, conv, question) if conv
           else w.genie.start_conversation_and_wait(SPACE_ID, question))
    st.session_state.conversation_id = msg.conversation_id
    message_id = getattr(msg, "message_id", None) or msg.id
    out = {}
    for att in msg.attachments or []:
        if att.text and att.text.content:
            out["text"] = att.text.content
        if att.query:
            out["description"], out["sql"] = att.query.description, att.query.query
            res = w.genie.get_message_attachment_query_result(
                SPACE_ID, msg.conversation_id, message_id, att.attachment_id).statement_response
            cols = [c.name for c in res.manifest.schema.columns]
            out["df"] = pd.DataFrame(res.result.data_array or [], columns=cols)
    if not out:
        out["text"] = f"Genie returned no answer (status: {msg.status})."
    return out


for turn in st.session_state.history:
    with st.chat_message(turn["role"]):
        render(turn["content"]) if turn["role"] == "assistant" else st.markdown(turn["content"])

if question := st.chat_input("e.g. Which line of business has the most open claims?"):
    st.session_state.history.append({"role": "user", "content": question})
    with st.chat_message("user"):
        st.markdown(question)
    with st.chat_message("assistant"):
        with st.spinner("Genie is thinking…"):
            try:
                answer = ask(question)
            except Exception as e:  # most often: missing CAN_RUN on the space or SELECT on the gold tables
                answer = {"text": f"⚠️ {type(e).__name__}: {str(e)[:400]}\n\n"
                                  "Check Module 6: CAN RUN on the Genie space, CAN USE on the warehouse, "
                                  "and SELECT on the gold tables for whoever the app runs as."}
        render(answer)
    st.session_state.history.append({"role": "assistant", "content": answer})
